def escape_control_characters(value: str, *, allow_line_breaks: bool = False) -> str:
    """Escape control characters in a string for safe single-line logging.

    The escaping is reversible with `unescape_control_characters`. Backslashes are
    escaped first so the representation is unambiguous even when the input already
    contains escape-like text. Non-control Unicode characters are left untouched.

    Args:
        value: string to escape.
        allow_line_breaks: preserve `LF` and `CRLF` as structural line breaks. Used
            only for text generated by the formatter, such as exception tracebacks.
    """
    parts: list[str] = []
    index = 0
    length = len(value)
    while index < length:
        char = value[index]
        if char == "\\":
            parts.append("\\\\")
        elif char == "\n":
            parts.append("\n" if allow_line_breaks else "\\n")
        elif char == "\r":
            if allow_line_breaks and index + 1 < length and value[index + 1] == "\n":
                parts.append("\r\n")
                index += 2
                continue
            parts.append("\\r")
        elif char == "\t":
            parts.append("\\t")
        elif char == "\b":
            parts.append("\\b")
        elif char == "\f":
            parts.append("\\f")
        else:
            code_point = ord(char)
            if (
                code_point < 0x20
                or 0x7F <= code_point <= 0x9F
                or char in _BIDI_CONTROL_CHARS
                or char in _LINE_SEPARATOR_CHARS
            ):
                parts.append(f"\\u{code_point:04x}")
            else:
                parts.append(char)
        index += 1
    return "".join(parts)


def unescape_control_characters(value: str) -> str:
    """Reverse `escape_control_characters`.

    Unknown escape sequences are preserved verbatim so this function can also be
    applied to strings that were not produced by the escaping function.
    """
    parts: list[str] = []
    index = 0
    length = len(value)
    simple_escapes = {
        "\\": "\\",
        '"': '"',
        "'": "'",
        "n": "\n",
        "r": "\r",
        "t": "\t",
        "b": "\b",
        "f": "\f",
        "0": "\x00",
    }
    while index < length:
        char = value[index]
        if char != "\\":
            parts.append(char)
            index += 1
            continue

        if index + 1 >= length:
            parts.append("\\")
            break

        escaped = value[index + 1]
        if escaped in simple_escapes:
            parts.append(simple_escapes[escaped])
            index += 2
            continue

        if escaped == "u" and index + 6 <= length:
            digits = value[index + 2 : index + 6]
            if all(digit in string.hexdigits for digit in digits):
                parts.append(chr(int(digits, 16)))
                index += 6
                continue

        if escaped == "x" and index + 4 <= length:
            digits = value[index + 2 : index + 4]
            if all(digit in string.hexdigits for digit in digits):
                parts.append(chr(int(digits, 16)))
                index += 4
                continue

        parts.append("\\")
        index += 1
    return "".join(parts)


def sanitize_json_value(value: Any) -> Any:
    """Recursively escape control characters in JSON-bound string values and keys.

    Formatter-generated exception and stack text is allowed to retain structural
    line breaks; every other string is escaped to a single logical line.
    """
    return _sanitize_json_value(value, allow_line_breaks=False, seen=set())


def _sanitize_json_value(value: Any, *, allow_line_breaks: bool, seen: set[int]) -> Any:
    if isinstance(value, _TrustedText):
        return escape_control_characters(value, allow_line_breaks=True)

    if isinstance(value, _TrustedTextList):
        value_id = id(value)
        if value_id in seen:
            return value
        seen.add(value_id)
        result = [_sanitize_json_value(item, allow_line_breaks=True, seen=seen) for item in value]
        seen.discard(value_id)
        return result

    if isinstance(value, str):
        return escape_control_characters(value, allow_line_breaks=allow_line_breaks)

    if isinstance(value, Mapping):
        value_id = id(value)
        if value_id in seen:
            return value
        seen.add(value_id)
        result = {
            (
                _sanitize_json_value(key, allow_line_breaks=False, seen=seen)
                if isinstance(key, str)
                else key
            ): _sanitize_json_value(item, allow_line_breaks=False, seen=seen)
            for key, item in value.items()
        }
        seen.discard(value_id)
        return result

    if isinstance(value, list):
        value_id = id(value)
        if value_id in seen:
            return value
        seen.add(value_id)
        result = [
            _sanitize_json_value(item, allow_line_breaks=allow_line_breaks, seen=seen)
            for item in value
        ]
        seen.discard(value_id)
        return result

    if isinstance(value, tuple):
        value_id = id(value)
        if value_id in seen:
            return value
        seen.add(value_id)
        result = tuple(
            _sanitize_json_value(item, allow_line_breaks=allow_line_breaks, seen=seen)
            for item in value
        )
        seen.discard(value_id)
        return result

    return value


def sanitizing_json_default(default: Callable[[Any], Any]) -> Callable[[Any], Any]:
    """Wrap a `json_default` callable so its return value follows safe-mode rules."""

    def sanitized_default(obj: Any) -> Any:
        return sanitize_json_value(default(obj))

    return sanitized_default


def _trusted_text(value: str | list[str]) -> _TrustedText | _TrustedTextList:
    if isinstance(value, list):
        return _TrustedTextList(value)
    return _TrustedText(value)


def merge_record_extra(
    record: logging.LogRecord,
    target: dict[Any, Any],
    reserved: Container[str],
    rename_fields: dict[str, str] | None = None,
) -> dict[Any, Any]:
    """
    Merges extra attributes from LogRecord object into target dictionary

    Args:
        record: logging.LogRecord
        target: dict to update
        reserved: dict or list with reserved keys to skip
        rename_fields: an optional dict, used to rename field names in the output.
            e.g. Rename `levelname` to `log.level`: `{'levelname': 'log.level'}`

    *Changed in 3.1*: `reserved` is now `Container[str]`.
    """
    if rename_fields is None:
        rename_fields = {}
    for key, value in record.__dict__.items():
        # this allows to have numeric keys
        if key not in reserved and not (hasattr(key, "startswith") and key.startswith("_")):
            target[rename_fields.get(key, key)] = value
    return target


