from __future__ import annotations

from typing import Any
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from alembic.autogenerate import RevisionContext


class CommandError(Exception):
    """Base command error for all exceptions"""


class DatabaseNotAtHead(CommandError):
    """Indicates the database is not at current head revisions.

    Raised by the :func:`.command.current` command when the
    :paramref:`.command.current.check_heads` parameter is used.

    .. versionadded:: 1.17.1

    """


class PlanError(CommandError):
    """Base class for migration planning errors."""


class AmbiguousPlanTargetError(PlanError):
    """Raised when a plan target resolves to multiple revisions."""


class UnknownPlanRevisionError(PlanError):
    """Raised when a planned revision cannot be resolved."""

    def __init__(
        self,
        message: str,
        revision: str | None = None,
        scope: str = "target",
    ) -> None:
        super().__init__(message)
        self.revision = revision
        self.scope = scope


class UnreachablePlanTargetError(PlanError):
    """Raised when a target cannot be reached from the current revisions."""


class InvalidPlanStateError(PlanError):
    """Raised when explicit current revisions do not describe valid heads."""


class AutogenerateDiffsDetected(CommandError):
    """Raised when diffs were detected by the :func:`.command.check`
    command.

    .. versionadded:: 1.9.0

    """

    def __init__(
        self,
        message: str,
        revision_context: RevisionContext,
        diffs: list[tuple[Any, ...]],
    ) -> None:
        super().__init__(message)
        self.revision_context = revision_context
        self.diffs = diffs
