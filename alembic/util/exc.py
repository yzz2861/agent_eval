from __future__ import annotations

from typing import Any
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from alembic.autogenerate import RevisionContext


class CommandError(Exception):
    """Base command error for all exceptions"""


class DatabaseNotAtHead(CommandError):
    """Indicates the database is not at current head revisions.

    Raised by the :func:`.command.current` command when the
    :paramref:`.command.current.check_heads` parameter is used.

    .. versionadded:: 1.17.1

    """


class PlanError(CommandError):
    """Base class for errors raised while computing a migration plan.

    .. versionadded:: 1.21.0

    """


class AmbiguousTargetError(PlanError):
    """The plan target resolved to more than one revision.

    Raised by :func:`.plan.build_plan` and the :func:`.command.plan`
    command when the target revision, e.g. ``head`` or a relative
    target, matches multiple revisions and cannot be narrowed down
    to a single one.

    .. versionadded:: 1.21.0

    """


class RevisionNotFoundError(PlanError):
    """A revision identifier in the plan target or the given current
    heads could not be resolved to any known revision.

    .. versionadded:: 1.21.0

    """


class UnreachableRangeError(PlanError):
    """The plan target is not reachable from the current heads.

    Raised when the requested target revision is not an
    ancestor/descendant of the current heads along the same branch,
    so no migration path exists between them.

    .. versionadded:: 1.21.0

    """


class AutogenerateDiffsDetected(CommandError):
    """Raised when diffs were detected by the :func:`.command.check`
    command.

    .. versionadded:: 1.9.0

    """

    def __init__(
        self,
        message: str,
        revision_context: RevisionContext,
        diffs: list[tuple[Any, ...]],
    ) -> None:
        super().__init__(message)
        self.revision_context = revision_context
        self.diffs = diffs
