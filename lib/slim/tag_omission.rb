# frozen_string_literal: true
module Slim
  # Optional compile time optimization which omits end tags where the
  # HTML specification allows it and the following output is known at
  # compile time. Enable it with
  #
  #   Slim::Engine.set_options omit_end_tags: true, format: :html
  #
  # The optimization is only applied if all of the following hold:
  #
  # * The format is :html (end tag omission is not allowed in XHTML/XML)
  # * Pretty printing is disabled (the inserted whitespace could move
  #   into the unclosed element and change the document tree)
  # * The element is not inside SVG or MathML (foreign content)
  # * The next output is either a compile time known tag which the HTML
  #   specification allows directly after the omitted end tag, or there
  #   is no more compile time known content in a known parent element
  #
  # Anything that might change the following output (control code,
  # loops, dynamic output, comments, non-empty text) keeps the end tag.
  #
  # @api private
  class TagOmission < Filter
    define_options :omit_end_tags, :format, :pretty

    # End tags which may be omitted if the element is immediately
    # followed by one of the listed tags. :any means any element tag
    # (used for elements which only must not be followed by whitespace
    # or a comment, both of which are never compile time known tags).
    FOLLOWERS = {
      'li' => %w[li],
      'dt' => %w[dt dd],
      'dd' => %w[dt dd],
      'p' => %w[address article aside blockquote details dialog div dl
                fieldset figcaption figure footer form h1 h2 h3 h4 h5 h6
                header hgroup hr main menu nav ol p pre section table ul],
      'rb' => %w[rb rt rtc rp],
      'rt' => %w[rt rp],
      'rtc' => %w[rb rtc],
      'rp' => %w[rt rp],
      'optgroup' => %w[optgroup],
      'option' => %w[option optgroup],
      'colgroup' => :any,
      'caption' => :any,
      'thead' => %w[tbody tfoot],
      'tbody' => %w[tbody tfoot],
      'tfoot' => %w[tbody],
      'tr' => %w[tr],
      'td' => %w[td th],
      'th' => %w[td th],
      'html' => :any,
      'head' => :any,
      'body' => :any
    }.freeze

    # End tags which may additionally be omitted if there is no more
    # content in the parent element.
    END_OF_PARENT = %w[li dt dd p rb rt rtc rp optgroup option
                       colgroup caption tbody tfoot tr td th head body].freeze

    # Parents which inhibit omitting the end tag of a p element at the
    # end of the parent content. Autonomous custom elements (tag names
    # containing a hyphen) are excluded as well.
    P_EXCLUDED_PARENTS = %w[a audio del ins map noscript video].freeze

    # Tags which start foreign content (SVG/MathML)
    FOREIGN_CONTENT = %w[svg math].freeze

    def initialize(opts = {})
      super
      format = options[:format]
      @omit = options[:omit_end_tags] && !options[:pretty] &&
              (format == :html || format == :html4 || format == :html5)
      @foreign = false
    end

    def call(exp)
      @omit ? super : exp
    end

    # Handle multi expression [:multi, *exps]
    def on_multi(*exps)
      compile_multi(exps, nil)
    end

    # Handle tag expression [:html, :tag, name, attrs, content]
    def on_html_tag(name, attrs, content = nil)
      name = name.to_s
      foreign = @foreign
      @foreign ||= FOREIGN_CONTENT.include?(name)
      result = if content
                 [:html, :tag, name, compile(attrs), compile_content(name, content)]
               else
                 [:html, :tag, name, compile(attrs)]
               end
      @foreign = foreign
      result
    end

    # Handle tag with omitted end tag (generated by this filter).
    # [:html, :tag, name, attrs] without content compiles to the
    # start tag only in :html format.
    def on_html_omit(name, attrs, content)
      [:multi,
       [:html, :tag, name, compile(attrs)],
       compile_content(name.to_s, content)]
    end

    private

    # Compile the content of an element, remembering the parent tag
    # name to prove no-more-content-in-the-parent-element.
    def compile_content(parent, content)
      content[0] == :multi ? compile_multi(content[1..-1], parent) : compile(content)
    end

    def compile_multi(exps, parent)
      result = [:multi]
      exps.each_with_index do |exp, i|
        if !@foreign && omissible?(exp)
          name = exp[2].to_s
          follower = next_significant(exps, i)
          if follower ? follow_ok?(name, follower) : end_ok?(name, parent)
            exp = [:html, :omit, exp[2], exp[3], exp[4]]
          end
        end
        result << compile(exp)
      end
      result
    end

    def omissible?(exp)
      exp[0] == :html && exp[1] == :tag && exp.length == 5 && FOLLOWERS.key?(exp[2].to_s)
    end

    # Next expression which produces output. Only newlines and empty
    # static content are skipped, everything else (code, dynamic
    # output, comments, non-empty text) is significant.
    def next_significant(exps, i)
      (i + 1).upto(exps.length - 1) do |j|
        exp = exps[j]
        return exp unless insignificant?(exp)
      end
      nil
    end

    def insignificant?(exp)
      case exp[0]
      when :newline
        true
      when :static
        exp[1].empty?
      when :multi
        exp[1..-1].all? {|e| insignificant?(e) }
      else
        false
      end
    end

    def follow_ok?(name, follower)
      return false unless follower[0] == :html && follower[1] == :tag
      followers = FOLLOWERS[name]
      followers == :any || followers.include?(follower[2].to_s)
    end

    def end_ok?(name, parent)
      return false unless parent && END_OF_PARENT.include?(name)
      name != 'p' || (!P_EXCLUDED_PARENTS.include?(parent) && !parent.include?('-'))
    end
  end
end
