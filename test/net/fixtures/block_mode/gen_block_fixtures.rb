# frozen_string_literal: true

# Generates the fixed Block Mode (RFC 959 MODE B) wire fixtures used by
# test_block_mode.rb.  Frames are packed directly from the protocol layout
# (1-byte descriptor + 16-bit big-endian count + body) so the fixture is an
# independent reference not produced by the code under test.

require "fileutils"

HERE = File.expand_path(__dir__)

EOR = 0x20
EOF = 0x40
RESTART = 0x80

def frame(descriptor, body)
  [descriptor, body.bytesize].pack("Cn") + body
end

def write_fixture(name, bytes)
  path = File.join(HERE, name)
  File.binwrite(path, bytes.b)
  warn "generated #{name}: #{bytes.bytesize} bytes"
end

# A single record spread over three blocks (exact block size first chunk),
# a restart marker, a second complete record, then trailing file bytes
# before the final EOR+EOF block.
record1 = "RECORD-ONE: " + ("a" * 200)
record2 = "RECORD-TWO: " + ("b" * 40)
trailing = "tail-data-cccccccc"

wire = String.new(encoding: Encoding::ASCII_8BIT)
wire << frame(0, record1.byteslice(0, 16))
wire << frame(0, record1.byteslice(16, 16))
wire << frame(EOR, record1.byteslice(32, record1.bytesize - 32))
wire << frame(RESTART, "checkpoint-7")
wire << frame(EOR, record2)
wire << frame(EOR | EOF, trailing)
write_fixture("sample.bin", wire)

# Variant where the end-of-data block also carries the final record bytes
# (EOF and EOR combined in a single frame), the shape emitted by some
# mainframe servers.
wire2 = String.new(encoding: Encoding::ASCII_8BIT)
wire2 << frame(EOR, record2)
wire2 << frame(EOR | EOF, trailing)
write_fixture("sample_eof_with_data.bin", wire2)

# Metadata describing the intended decode result.
metadata = {
  record1: record1,
  marker: "checkpoint-7",
  record2: record2,
  trailing: trailing,
  size: wire.bytesize
}
File.write(File.join(HERE, "sample.meta.rb"),
          "# generated by gen_block_fixtures.rb\n" +
          metadata.inspect + "\n")
