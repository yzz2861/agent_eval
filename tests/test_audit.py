class RevisionAuditTest(TestBase):
    def setUp(self):
        self.env = staging_env()
        self.cfg = _sqlite_testing_config()

    def tearDown(self):
        clear_staging_env()

    @property
    def _versions(self):
        return os.path.join(
            self.cfg.get_main_option("script_location"), "versions"
        )

    def _env_fixture(self, model_table, render_as_batch=False, extra=""):
        env_file_fixture(
            "\n\nfrom sqlalchemy import Column, Integer, MetaData, "
            "String, Table, Text, engine_from_config\n"
            "target_metadata = MetaData()\n"
            + model_table
            + "\nengine = engine_from_config(\n"
            "    config.get_section(config.config_ini_section), "
            "prefix='sqlalchemy.')\n"
            "connection = engine.connect()\n"
            "context.configure(connection=connection, "
            "target_metadata=target_metadata, "
            f"render_as_batch={render_as_batch!r}, {extra})\n"
            "try:\n    with context.begin_transaction():\n"
            "        context.run_migrations()\n"
            "finally:\n    connection.close()\n"
        )

    def _seed_db(self, *table_clauses):
        engine = create_engine(self.cfg.get_main_option("sqlalchemy.url"))
        metadata = MetaData()
        for clause in table_clauses:
            clause(metadata)
        metadata.create_all(engine)
        return engine

    def test_autogenerate_drop_column_inside_batch_blocks(self):
        self._seed_db(
            lambda m: Table(
                "account",
                m,
                Column("id", Integer, primary_key=True),
                Column("email", String(50)),
            ),
        )
        model = (
            "Table('account', target_metadata, "
            "Column('id', Integer, primary_key=True))\n"
        )
        self._env_fixture(model, render_as_batch=True)
        with expect_raises(AuditError) as raised:
            command.revision(self.cfg, autogenerate=True, revision_audit=True)
        report = raised.error.report
        column = next(
            f
            for f in report.findings
            if f.code == "drop_column" and f.branch == "upgrades"
        )
        eq_(column.severity, Severity.RISK)
        eq_(
            [e.kind for e in column.path],
            [
                "migration_script",
                "upgrade_ops",
                "modify_table_ops",
                "drop_column",
            ],
        )
        eq_([f for f in os.listdir(self._versions) if f.endswith(".py")], [])

    def test_report_only_still_writes_revision(self):
        self._seed_db(
            lambda m: Table("old", m, Column("id", Integer, primary_key=True)),
        )
        self._env_fixture("")
        command.revision(
            self.cfg,
            autogenerate=True,
            revision_audit=True,
            revision_audit_report_only=True,
        )
        eq_(
            len([f for f in os.listdir(self._versions) if f.endswith(".py")]),
            1,
        )

    def test_report_only_flag_alone_enables_audit(self):
        self._seed_db(
            lambda m: Table("old", m, Column("id", Integer, primary_key=True)),
        )
        self._env_fixture("")
