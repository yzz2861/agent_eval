def _script(upgrade_ops, multidb=False):
    downgrade = upgrade_ops.reverse()
    if multidb:
        up2 = ops.UpgradeOps([], upgrade_token="engine2_upgrades")
        down2 = ops.DowngradeOps([], downgrade_token="engine2_downgrades")
        return ops.MigrationScript(
            "r1",
            [upgrade_ops, up2],
            [downgrade, down2],
        )
    return ops.MigrationScript("r1", upgrade_ops, downgrade)


class WalkTest(TestBase):
    def test_walk_covers_batch_and_branches(self):
        drop_column = ops.DropColumnOp.from_column_and_tablename(
            None, "account", Column("email", String())
        )
        upgrade = ops.UpgradeOps(
            [
                ops.DropTableOp("accounts"),
                ops.ModifyTableOps("account", [drop_column]),
            ]
        )
        script = _script(upgrade)

        report = audit_migration_script(script)
        codes = {(f.code, f.branch, f.operation) for f in report.findings}
        is_true(("drop_table", "upgrades", "DropTableOp") in codes)
        is_true(("drop_column", "upgrades", "DropColumnOp") in codes)

        column_finding = next(
            f
            for f in report.findings
            if f.code == "drop_column" and f.branch == "upgrades"
        )
        eq_(
            [entry.kind for entry in column_finding.path],
            [
                "migration_script",
                "upgrade_ops",
                "modify_table_ops",
                "drop_column",
            ],
        )
        eq_(column_finding.path[-2].name, "account")
        eq_(column_finding.object_name, "account.email")

    def test_downgrade_drop_is_info(self):
        # a hand-written downgrade that itself drops a table reports at
        # INFO (downgrades mirror the forward/upgrade stream), but the path
        # still records the downgrade branch explicitly.
        script = ops.MigrationScript(
            "r1",
            ops.UpgradeOps([]),
            ops.DowngradeOps([ops.DropTableOp("accounts")]),
        )
        report = audit_migration_script(script)
        downgrade = report.findings_at([Severity.INFO])
        eq_(len(downgrade), 1)
        eq_(downgrade[0].code, "drop_table")
        eq_(downgrade[0].branch, "downgrades")
        eq_(downgrade[0].path[1].kind, "downgrade_ops")

    def test_autogenerated_downgrade_create_table_is_silent(self):
        upgrade = ops.UpgradeOps([ops.DropTableOp("accounts")])
        report = audit_migration_script(_script(upgrade))
        branches = {f.branch for f in report.findings}
        eq_(branches, {"upgrades"})

    def test_multidb_branches_are_separate(self):
        upgrade = ops.UpgradeOps(
            [ops.DropTableOp("t1")],
            upgrade_token="engine1_upgrades",
        )
        script = _script(upgrade, multidb=True)
        report = audit_migration_script(
            script,
            dialect_names={
                "engine1_upgrades": "postgresql",
                "engine2_upgrades": "sqlite",
            },
        )
        risks = report.findings_at([Severity.RISK])
        eq_(len(risks), 1)
        eq_(risks[0].branch, "engine1_upgrades")
        eq_(risks[0].dialect_name, "postgresql")


class AlterColumnTypeTest(TestBase):
    def _alter(self, existing, new):
        return ops.AlterColumnOp(
            "t", "c", existing_type=existing, modify_type=new
        )

    def test_integer_narrowing_is_warning(self):
        report = audit_migration_script(
            _script(ops.UpgradeOps([self._alter(Integer(), SmallInteger())]))
        )
        findings = [f for f in report.findings if f.branch == "upgrades"]
        eq_(len(findings), 1)
        eq_(findings[0].severity, Severity.WARNING)
        eq_(findings[0].code, "alter_column_type")

    def test_integer_widening_is_safe(self):
        report = audit_migration_script(
            _script(ops.UpgradeOps([self._alter(SmallInteger(), Integer())]))
        )
        eq_(report.findings_at([Severity.WARNING, Severity.RISK]), [])

    def test_string_length_narrowing(self):
        report = audit_migration_script(
            _script(ops.UpgradeOps([self._alter(String(50), String(20))]))
        )
        findings = report.findings_at([Severity.WARNING])
        eq_(len(findings), 1)
        is_true("length reduced" in findings[0].message)

    def test_string_to_text_is_unknown_not_safe(self):
        report = audit_migration_script(
            _script(ops.UpgradeOps([self._alter(String(20), Text())]))
        )
        findings = [
            f
            for f in report.findings_at([Severity.UNKNOWN])
            if f.branch == "upgrades"
        ]
        eq_(len(findings), 1)

    def test_missing_existing_type_is_unknown(self):
        op = ops.AlterColumnOp("t", "c", modify_type=String(10))
        report = audit_migration_script(_script(ops.UpgradeOps([op])))
        findings = [f for f in report.findings if f.branch == "upgrades"]
        eq_(len(findings), 1)
        eq_(findings[0].severity, Severity.UNKNOWN)
        is_true("existing type information missing" in findings[0].message)

    def test_nulltype_is_unknown(self):
        op = ops.AlterColumnOp(
            "t",
            "c",
            existing_type=sqltypes.NULLTYPE,
            modify_type=String(10),
        )
        report = audit_migration_script(_script(ops.UpgradeOps([op])))
        findings = [
            f
            for f in report.findings_at([Severity.UNKNOWN])
            if f.branch == "upgrades"
        ]
        eq_(len(findings), 1)

    def test_alter_column_without_type_change_is_silent(self):
        op = ops.AlterColumnOp(
            "t", "c", modify_nullable=False, existing_nullable=True
        )
        report = audit_migration_script(_script(ops.UpgradeOps([op])))
        eq_(report.findings, [])

    def test_type_class_accepted(self):
        op = ops.AlterColumnOp(
            "t", "c", existing_type=String, modify_type=String
        )
        report = audit_migration_script(
            _script(ops.UpgradeOps([op])),
        )
        # no length info on either side -> same class, safe, no finding
        eq_(report.findings_at([Severity.UNKNOWN]), [])


