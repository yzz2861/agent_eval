"""Rendering helpers for evidence-bound policy reports."""

import json
from typing import Any

from regipy.policy.models import PolicyReport, _json_safe


def _format_value(value: Any) -> str:
    if isinstance(value, str):
        return value
    return json.dumps(_json_safe(value), ensure_ascii=False, sort_keys=True)


def _format_related(value: Any) -> str:
    return json.dumps(_json_safe(value), ensure_ascii=False, sort_keys=True, indent=2)


def render_markdown(report: PolicyReport) -> str:
    """Render a policy report as a reviewable Markdown document."""
    summary = report.summary
    lines = [
        "# Policy context report",
        "",
        f"Generated by `{report.generated_by}` (schema `{report.schema_version}`).",
        "",
        "Every explanation below names the delegated role it applies to, the evidence item(s) "
        "it came from, and the conditions that were evaluated. Contexts that could not be "
        "safely bound are listed separately.",
        "",
        "## Summary",
        "",
        f"- Roles: {summary['roles']}",
        f"- Evidence items: {summary['evidence']}",
        f"- Policy records: {summary['records']}",
        f"- Explanations: {summary['explanations']} ({summary['explanations_by_status']})",
        f"- Unbound contexts: {summary['unbound_contexts']} ({summary['unbound_by_reason']})",
        "",
        "## Explanations",
        "",
    ]

    if not report.explanations:
        lines.extend(["_No explanations were produced._", ""])

    for explanation in report.explanations:
        lines.extend(
            [
                f"### `{explanation.policy_id}` / role `{explanation.role_id}` (`{explanation.status}`)",
                "",
                f"- Conclusion: {_format_value(explanation.conclusion)}",
                f"- Role kind: `{explanation.role_kind}`",
                f"- Login context: `{explanation.login_context}`",
                f"- Rule: `{explanation.rule_id}`",
                f"- Combination: `{explanation.combination}` (`{explanation.condition_logic}`)",
            ]
        )
        if explanation.combination_expression:
            lines.append(f"- Combination expression: {explanation.combination_expression}")
        if explanation.overridden_by:
            lines.append(f"- Overridden by record: `{explanation.overridden_by}`")
        lines.append("- Evidence:")
        if not explanation.evidence:
            lines.append("  - _none_")
        for item in explanation.evidence:
            details = [
                f"  - **{item.get('selection', 'selected')}** `{item.get('evidence_id')}`",
                f"    - Hive: `{item.get('hive_path')}` (type `{item.get('hive_type')}`)",
                f"    - Key: `{item.get('key_path')}`",
                (f"    - Value: `{item.get('value_name')}` = `{_format_value(item.get('value'))}` ({item.get('value_type')})"),
                f"    - Last write: `{item.get('last_write')}`",
                f"    - Record id: `{item.get('record_id')}`",
            ]
            lines.extend(details)
        lines.append(f"- Conditions (`{explanation.condition_logic}`):")
        if not explanation.conditions:
            lines.append("  - _none_")
        for condition in explanation.conditions:
            marker = "x" if condition.get("satisfied") else " "
            lines.append(f"  - [{marker}] {condition.get('expression')} (`{condition.get('kind')}`)")
        lines.extend([f"- Explanation: {explanation.explanation}", ""])

    lines.extend(["## Unbound contexts", ""])
    if not report.unbound_contexts:
        lines.extend(["_No unbound contexts._", ""])
    for item in report.unbound_contexts:
        lines.extend(
            [
                f"### `{item.reason}` (`{item.context_id}`)",
                "",
                f"- Detail: {item.detail}",
                f"- Role: `{item.role_id}`",
                f"- Policy: `{item.policy_id}`",
                f"- Evidence: `{item.evidence_id}`",
                f"- Record: `{item.record_id}`",
            ]
        )
        if item.related:
            lines.extend(["- Related:", "", "```json", _format_related(item.related), "```"])
        lines.append("")

    lines.extend(["## Delegated roles", ""])
    for role in report.roles:
        lines.append(
            f"- `{role.role_id}` — kind `{role.kind}`, login context `{role.login_context}`, "
            f"evidence `{role.evidence_ids}`, source `{role.source}`"
        )
    if not report.roles:
        lines.append("_No roles supplied._")

    lines.extend(["", "## Evidence", ""])
    for evidence in report.evidence:
        lines.append(
            f"- `{evidence.evidence_id}` — `{evidence.hive_path}` (type `{evidence.hive_type}`, "
            f"scope `{evidence.scope}`, sha256 `{evidence.sha256}`)"
        )
    if not report.evidence:
        lines.append("_No evidence supplied._")

    lines.append("")
    return "\n".join(lines)


def render_report(report: PolicyReport, fmt: str = "markdown") -> str:
    """Render a report as ``json`` or ``markdown``."""
    normalized = (fmt or "markdown").lower()
    if normalized == "json":
        return report.to_json()
    if normalized in ("md", "markdown"):
        return render_markdown(report)
    raise ValueError(f"unsupported report format: {fmt!r}")
